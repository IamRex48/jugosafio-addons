const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('fonyx', {
  state: () => ipcRenderer.invoke('state'),
  bankStatus: () => ipcRenderer.invoke('bank:status'),
  setupStatus: () => ipcRenderer.invoke('setup:status'),
  setupSelectData: folder => ipcRenderer.invoke('setup:select-data',folder),
  setupOpenGame: () => ipcRenderer.invoke('setup:open-game'),
  setupRefresh: () => ipcRenderer.invoke('setup:refresh'),
  setupChoose: kind => ipcRenderer.invoke('setup:choose',kind),
  setupAudio: value => ipcRenderer.invoke('setup:audio',value),
  setupFinish: () => ipcRenderer.invoke('setup:finish'),
  accountConnect: () => ipcRenderer.invoke('account:connect'),
  accountCancel: () => ipcRenderer.invoke('account:cancel'),
  audioPrepare: () => ipcRenderer.invoke('audio:prepare'),
  window: action => ipcRenderer.invoke('window', action),
  social: key => ipcRenderer.invoke('social', key),
  setUserView: value => ipcRenderer.invoke('admin:userView',value),
  refreshAdministrators: () => ipcRenderer.invoke('admins:refresh'),
  changeAdministrator: (name,grant) => ipcRenderer.invoke('admins:change',name,grant),
  onAdministratorsChanged: callback => {const listener=()=>callback();ipcRenderer.on('admin:changed',listener);return ()=>ipcRenderer.removeListener('admin:changed',listener);},
  applyHotkeys: () => ipcRenderer.invoke('hotkeys:apply'),
  onVoiceCommand: callback => {const listener=(_event,value)=>callback(value);ipcRenderer.on('voice:command',listener);return ()=>ipcRenderer.removeListener('voice:command',listener);},
  onNavigate: callback => {const listener=(_event,value)=>callback(value);ipcRenderer.on('navigate',listener);return ()=>ipcRenderer.removeListener('navigate',listener);},
  ping: id => ipcRenderer.invoke('ping', id),
  play: id => ipcRenderer.invoke('play', id, true),
  update: id => ipcRenderer.invoke('play', id, false),
  saveSettings: value => ipcRenderer.invoke('settings:save', value),
  chooseAvatar: (profile, skin = false) => ipcRenderer.invoke('settings:avatar', profile, skin),
  chooseFolder: () => ipcRenderer.invoke('settings:folder'),
  saveContent: value => ipcRenderer.invoke('admin:save', value),
  exportContent: () => ipcRenderer.invoke('admin:export'),
  refreshContent: () => ipcRenderer.invoke('admin:refresh'),
  voicePrepare: eventId => ipcRenderer.invoke('voice:prepare',eventId),
  voiceConnect: options => ipcRenderer.invoke('voice:connect',options),
  voiceDisconnect: () => ipcRenderer.invoke('voice:disconnect'),
  voiceSignal: (peer,payload) => ipcRenderer.invoke('voice:signal',peer,payload),
  voiceControls: values => ipcRenderer.invoke('voice:controls',values),
  voiceLevel: value => ipcRenderer.invoke('voice:level',value),
  voiceCopyCode: () => ipcRenderer.invoke('voice:copy-code'),
  voiceMode: mode => ipcRenderer.invoke('voice:mode',mode),
  voiceMicrosoft: () => ipcRenderer.invoke('voice:microsoft'),
  voiceSignOut: () => ipcRenderer.invoke('voice:sign-out'),
  onVoice: callback => {const listener=(_event,value)=>callback(value);ipcRenderer.on('voice:event',listener);return ()=>ipcRenderer.removeListener('voice:event',listener);},
  githubConnect: (token,remember) => ipcRenderer.invoke('github:connect',token,remember),
  githubDisconnect: () => ipcRenderer.invoke('github:disconnect'),
  githubTokenHelp: () => ipcRenderer.invoke('github:token-help'),
  githubAddon: (eventId,replaceAll=false) => ipcRenderer.invoke('github:addon',eventId,replaceAll),
  githubPacks: id => ipcRenderer.invoke('github:packs',id),
  githubRemovePack: (id,uuid) => ipcRenderer.invoke('github:remove-pack',id,uuid),
  githubExportPacks: id => ipcRenderer.invoke('github:export-packs',id),
  githubClearAddon: () => ipcRenderer.invoke('github:clear-addon'),
  githubPublish: (id,includePacks=true) => ipcRenderer.invoke('github:publish',id,includePacks),
  onGithubProgress: callback => { const listener=(_event,message)=>callback(message);ipcRenderer.on('github:progress',listener);return ()=>ipcRenderer.removeListener('github:progress',listener); },
  onProgress: callback => { const listener = (_event, progress) => callback(progress); ipcRenderer.on('update:progress', listener); return () => ipcRenderer.removeListener('update:progress', listener); }
});
